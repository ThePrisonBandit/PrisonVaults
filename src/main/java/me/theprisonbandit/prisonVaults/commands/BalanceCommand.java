package me.theprisonbandit.prisonVaults.commands;

import me.theprisonbandit.prisonVaults.PrisonVaults;
import me.theprisonbandit.prisonVaults.utils.NumberUtils; // <--- NEW IMPORT
import org.bukkit.ChatColor;
import org.bukkit.command.Command;
import org.bukkit.command.CommandExecutor;
import org.bukkit.command.CommandSender;
import org.bukkit.entity.Player;

public class BalanceCommand implements CommandExecutor {

    private final PrisonVaults plugin;

    public BalanceCommand(PrisonVaults plugin) {
        this.plugin = plugin;
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        if (!(sender instanceof Player)) return true;
        Player player = (Player) sender;

        double bal = plugin.getBalance(player);

        // <--- UPDATED LINE BELOW --->
        player.sendMessage(ChatColor.GREEN + "Balance: " + ChatColor.GOLD + "$" + NumberUtils.format(bal));

        return true;
    }
}